// Copies the path data of the Phosphor (regular) icons the app uses into icons.generated.ts, so
// the app ships a dozen icons instead of an icon library. Add a name to ICONS and run: pnpm gen:icons
import { readFileSync, writeFileSync } from 'node:fs';

export const ICONS = [
  'arrow-left', 'cake', 'calendar-blank', 'caret-left', 'caret-right', 'check', 'house', 'magnifying-glass',
  'map-pin', 'phone', 'plus', 'tree-structure', 'user', 'users-three', 'warning-circle', 'whatsapp-logo',
  'wifi-slash', 'x',
] as const;

const dir = new URL('../../../node_modules/@phosphor-icons/core/assets/regular/', import.meta.url).pathname;
const out: Record<string, string[]> = {};
for (const name of ICONS) {
  const svg = readFileSync(`${dir}${name}.svg`, 'utf8');
  if (!svg.includes('viewBox="0 0 256 256"')) throw new Error(`${name}: unexpected viewBox`);
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1] ?? '');
  if (!paths.length || /<(circle|rect|line|polyline|polygon|ellipse)\b/.test(svg)) throw new Error(`${name}: not path-only`);
  out[name] = paths;
}
const body = `// GENERATED by packages/ui/scripts/gen-icons.ts from @phosphor-icons/core (MIT). Do not edit by hand.
// Phosphor regular, 256-unit viewBox, filled outlines.
export const ICON_PATHS = ${JSON.stringify(out, null, 2)} as const;
export type IconName = keyof typeof ICON_PATHS;
`;
writeFileSync(new URL('../icons.generated.ts', import.meta.url), body);
console.log(`wrote icons.generated.ts (${ICONS.length} icons)`);
