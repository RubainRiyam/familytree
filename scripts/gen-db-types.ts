// Reads the JSON from scripts/db-introspect.sql on stdin and prints a Database type in the
// same shape as `supabase gen types typescript`, so supabase-js calls are typed. Run through
// `pnpm gen:types` (which uses the throwaway database from scripts/test-db.sh). Once the Supabase
// project exists, the official generator can replace this; the output shape is compatible.
import { readFileSync } from 'node:fs';

type Col = { name: string; udt: string; elem: string | null; nullable: boolean; hasDefault: boolean; generated: boolean };
type Rel = { foreignKeyName: string; columns: string[]; referencedRelation: string; referencedColumns: string[]; isOneToOne: boolean };
type Table = { name: string; kind: string; columns: Col[]; relationships: Rel[] };
type Arg = { name: string | null; udt: string; elem: string | null; mode: string };
type Fn = { name: string; setof: boolean; ret: string; ret_elem: string | null; args: Arg[] | null; ndefaults: number; nargs: number };
type Schema = { tables: Table[]; enums: Record<string, string[]>; functions: Fn[] };

export function tsType(udt: string, elem: string | null, enums: Record<string, string[]>): string {
  if (elem) return `${tsType(elem, null, enums)}[]`;
  if (enums[udt]) return `Database['public']['Enums']['${udt}']`;
  if (/^(int2|int4|int8|float4|float8|numeric|oid)$/.test(udt)) return 'number';
  if (udt === 'bool') return 'boolean';
  if (/^jsonb?$/.test(udt)) return 'Json';
  if (udt === 'void') return 'undefined';
  if (/^(text|varchar|bpchar|char|citext|uuid|date|time|timetz|timestamp|timestamptz|interval|inet|cidr|bytea|tsvector|name)$/.test(udt)) return 'string';
  return 'unknown';
}

const key = (k: string) => (/^[A-Za-z_]\w*$/.test(k) ? k : JSON.stringify(k));

export function render(s: Schema): string {
  const L: string[] = [];
  const t = (c: Col) => tsType(c.udt, c.elem, s.enums);
  L.push('// GENERATED by scripts/gen-db-types.ts from the migrations (pnpm gen:types). Do not edit by hand.');
  L.push('export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];', '');
  L.push('export type Database = {', '  public: {');
  for (const [label, kinds] of [['Tables', ['r', 'p']], ['Views', ['v', 'm']]] as const) {
    const rows = s.tables.filter((x) => (kinds as readonly string[]).includes(x.kind));
    if (!rows.length) { L.push(`    ${label}: { [_ in never]: never };`); continue; }
    L.push(`    ${label}: {`);
    for (const tb of rows) {
      L.push(`      ${key(tb.name)}: {`);
      L.push('        Row: {', ...tb.columns.map((c) => `          ${key(c.name)}: ${t(c)}${c.nullable ? ' | null' : ''};`), '        };');
      if (label === 'Tables') {
        const ins = tb.columns.filter((c) => !c.generated);
        L.push('        Insert: {', ...ins.map((c) => `          ${key(c.name)}${c.nullable || c.hasDefault ? '?' : ''}: ${t(c)}${c.nullable ? ' | null' : ''};`), '        };');
        L.push('        Update: {', ...ins.map((c) => `          ${key(c.name)}?: ${t(c)}${c.nullable ? ' | null' : ''};`), '        };');
      }
      L.push('        Relationships: [');
      for (const r of tb.relationships) {
        L.push('          {', `            foreignKeyName: ${JSON.stringify(r.foreignKeyName)};`, `            columns: ${JSON.stringify(r.columns)};`,
          `            isOneToOne: ${r.isOneToOne};`, `            referencedRelation: ${JSON.stringify(r.referencedRelation)};`,
          `            referencedColumns: ${JSON.stringify(r.referencedColumns)};`, '          },');
      }
      L.push('        ];', '      };');
    }
    L.push('    };');
  }
  L.push('    Functions: {');
  for (const f of s.functions) {
    const args = f.args ?? [];
    const ins = args.filter((a) => a.mode === 'i' || a.mode === 'b');
    const outs = args.filter((a) => a.mode === 't' || a.mode === 'o' || a.mode === 'b');
    const firstDefault = f.nargs - f.ndefaults;
    const argT = ins.length
      ? `{ ${ins.map((a, i) => `${key(a.name ?? `arg${i}`)}${i >= firstDefault ? '?' : ''}: ${tsType(a.udt, a.elem, s.enums)}`).join('; ')} }`
      : 'never';
    let ret: string;
    if (outs.length && f.ret === 'record') {
      ret = `{ ${outs.map((a) => `${key(a.name ?? 'value')}: ${tsType(a.udt, a.elem, s.enums)}`).join('; ')} }${f.setof ? '[]' : ''}`;
    } else {
      ret = tsType(f.ret, f.ret_elem, s.enums) + (f.setof ? '[]' : '');
    }
    L.push(`      ${key(f.name)}: { Args: ${argT}; Returns: ${ret} };`);
  }
  L.push('    };');
  const enumNames = Object.keys(s.enums);
  L.push(enumNames.length ? `    Enums: { ${enumNames.map((e) => `${key(e)}: ${(s.enums[e] ?? []).map((v) => JSON.stringify(v)).join(' | ')}`).join('; ')} };` : '    Enums: { [_ in never]: never };');
  L.push('    CompositeTypes: { [_ in never]: never };', '  };', '};', '');
  L.push("type PublicSchema = Database['public'];");
  L.push("export type Tables<T extends keyof PublicSchema['Tables']> = PublicSchema['Tables'][T]['Row'];");
  L.push("export type TablesInsert<T extends keyof PublicSchema['Tables']> = PublicSchema['Tables'][T]['Insert'];");
  L.push("export type TablesUpdate<T extends keyof PublicSchema['Tables']> = PublicSchema['Tables'][T]['Update'];");
  L.push("export type Functions<T extends keyof PublicSchema['Functions']> = PublicSchema['Functions'][T];", '');
  return L.join('\n');
}

if (import.meta.main) process.stdout.write(render(JSON.parse(readFileSync(0, 'utf8')) as Schema));
